/** Десятый канал по стандарту всегда ударные, program там значит набор. */
export const DRUM_CHANNEL = 9;

export function instrumentName(program: number | null, channel: number): string | null {
    if (channel === DRUM_CHANNEL) return "Ударные";
    if (program === null) return null;
    return GM_NAMES[program] ?? null;
}
