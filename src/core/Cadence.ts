/**
 * Ход дорогой работы: делать её не чаще заданной частоты.
 *
 * Свечение размыто и инерционно — обновлять его каждый кадр незачем: при
 * 60 Гц половина этой работы уходит в кадр, который глаз от соседнего не
 * отличит. Считать пропуски кадрами, а не временем, нельзя: на слабой машине
 * кадров и так шесть в секунду, и «через кадр» превратилось бы в моргание.
 * Поэтому мера — секунды: пока кадры длиннее периода, работа идёт каждый.
 */
export class Cadence {
    /** Время с прошлой работы. Бесконечность — первый кадр не ждёт. */
    private waited = Infinity;

    constructor(private readonly hz: number) {}

    /** Кадр длиной `dt` прошёл: пора ли делать работу? */
    due(dt: number): boolean {
        this.waited += dt;
        if (this.waited < 1 / this.hz) return false;
        // Остаток не переносится: иначе период дополз бы до длины кадра и
        // работа снова пошла бы каждый кадр — ровно то, чего избегаем.
        this.waited = 0;
        return true;
    }

    /** Работа обязана случиться в ближайшем кадре: холст перестроен, ждать нечего. */
    force(): void {
        this.waited = Infinity;
    }
}
