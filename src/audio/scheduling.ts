/**
 * Упреждение звука. Ноты файла запускаются из кадрового цикла, поэтому их
 * атака дрожит на длину кадра: две тридцать вторые вместо ровных 62 мс
 * расходятся то на 50, то на 83. Лечится не задержкой, а тем, что каждая нота
 * возвращается в свой музыкальный момент: сэмплер знает, сколько ей уже
 * «должно быть» на момент кадра, и стартует её настолько же раньше.
 *
 * Постоянные 50 мс задержки взамен дрожи слух не замечает: порог, за которым
 * звук начинает отставать от картинки заметно, втрое дальше.
 */
export const LOOKAHEAD = 0.05;

/**
 * Когда начаться голосу. `age` — возраст ноты внутри кадра в секундах;
 * `null` означает живую игру, которой упреждение не нужно.
 */
export function startAt(now: number, age: number | null, lookahead = LOOKAHEAD): number {
    if (age === null) return now;
    // Кадр длиннее упреждения: раньше «сейчас» начать всё равно нельзя.
    return now + Math.max(0, lookahead - Math.max(0, age));
}
